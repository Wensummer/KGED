"""
Build split-aware evaluation sets (true + anomaly) for a fair protocol.

Why:
- The provided anomaly set (dataset/<dataset>/mixture_anomaly/<ratio>/anomaly_triples.txt)
  is generated by sampling from the full KG (train+dev+test) in CCA code.
- To evaluate generalization, we should train on train split and evaluate on dev/test,
  so we need to filter anomalies by the SOURCE triple split.

This script creates:
  <output_dir>/true.jsonl    : triples from <split>.txt
  <output_dir>/anomaly.jsonl : anomalies whose corresponding selected_triples belong to <split>.txt

Usage:
  python3 -m rag_kge.make_split_eval_sets \
    --dataset wn18rr \
    --split test \
    --anomaly_dir dataset/wn18rr/mixture_anomaly/5 \
    --output_dir rag_kge/output/wn18rr/eval_test_5
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Iterable, List, Tuple


def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(description="Build split-aware eval sets (true+anomaly).")
    p.add_argument("--dataset", type=str, default="wn18rr", choices=["wn18rr", "fb15k-237", "nell995"])
    p.add_argument("--split", type=str, required=True, choices=["train", "dev", "test"])
    p.add_argument(
        "--anomaly_dir",
        type=str,
        required=True,
        help="Path like dataset/<dataset>/mixture_anomaly/<ratio> containing selected_triples.txt and anomaly_triples.txt",
    )
    p.add_argument("--output_dir", type=str, required=True)
    return p.parse_args()


def read_txt_triples(path: Path) -> List[Tuple[str, str, str]]:
    triples: List[Tuple[str, str, str]] = []
    with path.open("r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            h, r, t = line.split("\t")
            triples.append((h, r, t))
    return triples


def write_jsonl(path: Path, records: Iterable[dict]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as f:
        for obj in records:
            f.write(json.dumps(obj, ensure_ascii=False) + "\n")


def main() -> None:
    args = parse_args()

    root = Path(__file__).resolve().parent.parent
    dataset_dir = root / "dataset" / args.dataset

    split_txt = dataset_dir / f"{args.split}.txt"
    if not split_txt.exists():
        raise FileNotFoundError(f"Split file not found: {split_txt}")
    split_triples = read_txt_triples(split_txt)
    split_set = set(split_triples)

    anomaly_dir = Path(args.anomaly_dir)
    sel_path = anomaly_dir / "selected_triples.txt"
    anom_path = anomaly_dir / "anomaly_triples.txt"
    if not sel_path.exists() or not anom_path.exists():
        raise FileNotFoundError(f"Expected {sel_path} and {anom_path}")

    selected = read_txt_triples(sel_path)
    anomalies = read_txt_triples(anom_path)
    if len(selected) != len(anomalies):
        raise ValueError(
            f"selected_triples and anomaly_triples length mismatch: {len(selected)} vs {len(anomalies)}"
        )

    out_dir = Path(args.output_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    true_out = out_dir / "true.jsonl"
    anom_out = out_dir / "anomaly.jsonl"
    meta_out = out_dir / "meta.json"

    # true
    true_recs = ({"h_id": h, "r_id": r, "t_id": t} for (h, r, t) in split_triples)
    write_jsonl(true_out, true_recs)

    # anomaly filtered by SOURCE split
    anom_recs = []
    for (sh, sr, st), (ah, ar, at) in zip(selected, anomalies):
        if (sh, sr, st) not in split_set:
            continue
        anom_recs.append(
            {
                "h_id": ah,
                "r_id": ar,
                "t_id": at,
                "source_h_id": sh,
                "source_r_id": sr,
                "source_t_id": st,
                "source_split": args.split,
            }
        )
    write_jsonl(anom_out, anom_recs)

    meta = {
        "dataset": args.dataset,
        "split": args.split,
        "true_triples": len(split_triples),
        "anomaly_triples": len(anom_recs),
        "anomaly_ratio": (len(anom_recs) / max(1, len(split_triples))),
        "anomaly_dir": str(anomaly_dir),
    }
    meta_out.write_text(json.dumps(meta, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

    print(f"Wrote: {true_out} ({len(split_triples)} true)")
    print(f"Wrote: {anom_out} ({len(anom_recs)} anomaly, filtered by source split)")
    print(f"Wrote: {meta_out}")


if __name__ == "__main__":
    main()

